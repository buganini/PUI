const assert=require('node:assert/strict'),path=require('node:path');
const {createRequire}=require('node:module');
const requireBrowser=process.env.PUI_BROWSER_MODULES
 ? createRequire(path.join(process.env.PUI_BROWSER_MODULES,'package.json')) : require;
const {chromium}=requireBrowser('playwright');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.PUI_CHROME || '/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
 try {
  const page=await browser.newPage(),errors=[];page.setDefaultTimeout(10000);
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.PUI_WEB_URL || 'http://localhost:8866/pui/');
  await page.getByRole('button',{name:'Checkbox',exact:true}).click();
  await page.getByRole('checkbox',{name:'checkbox 1-1',exact:true}).uncheck();
  await page.getByText('Model value 1: False',{exact:true}).waitFor();
  assert.equal(await page.getByRole('checkbox',{name:'checkbox 1-2',exact:true}).isChecked(),false);
  await page.getByRole('checkbox',{name:'checkbox 3',exact:true}).check();
  await page.getByText("List value: ['value 3']",{exact:true}).waitFor();
  await page.getByRole('checkbox',{name:'checkbox 6',exact:true}).check();
  await page.getByText("Dict value: {'value 6': True}",{exact:true}).waitFor();
  await page.getByRole('button',{name:'RadioButton',exact:true}).click();
  await page.getByRole('radio',{name:'A',exact:true}).check();
  await page.getByText('Model value: a',{exact:true}).waitFor();
  await page.getByRole('radio',{name:'A',exact:true}).press('ArrowDown');
  await page.getByText('Model value: b',{exact:true}).waitFor();
  assert.equal(await page.getByRole('radio',{name:'A',exact:true}).isChecked(),false);
  await page.getByRole('button',{name:'Combobox',exact:true}).click();
  const select=page.locator('.pui-ComboBox select:visible'),input=page.locator('.pui-ComboBox input:visible');
  await select.selectOption({label:'Item 2'});
  await page.getByText('Text: Value 2',{exact:true}).waitFor();
  await input.fill('new custom value');
  assert.equal(await page.getByText('Text: Value 2',{exact:true}).count(),1);
  await input.press('Enter');
  await page.getByText('Text: new custom value',{exact:true}).waitFor();
  await input.fill('Item 3');await input.press('Tab');
  await page.getByText('Index: 2',{exact:true}).waitFor();
  await page.getByText('Text: Value 3',{exact:true}).waitFor();
  assert.equal(await input.inputValue(),'Item 3');
  await page.evaluate(async()=>{
   const {Renderer}=await import(document.querySelector('script[type=module]').src);
   const host=document.createElement('div');document.body.append(host);
   const actions=[],r=new Renderer(host,(kind,body,sent)=>{actions.push({kind,body});sent?.(actions.length);});
   const check=(v,m)=>{if(!v)throw new Error(m);};
   const node=(id,type,props={},children=[],events={})=>({id,type,props,children,events,layout:{},style:{},bindings:{}});
   const ref={object_id:'42',kind:'attr',key:'value'},slot={ref,token:'slot',value_rev:1,value:false};
   const binding=id=>({ref,slot_token:'slot',token:'attachment-'+id,writable:true});
   const checkbox=node('check','Checkbox',{text:'check',checked:false},[],{toggle:'toggle'});checkbox.bindings.model=binding('check');
   const a=node('a','RadioButton',{text:'A',checked:true},[],{activate:'a'});a.bindings.model=binding('a');
   const b=node('b','RadioButton',{text:'B',checked:false},[],{activate:'b'});b.bindings.model=binding('b');
   const first=node('one','ComboBoxItem',{text:'same'}),second=node('two','ComboBoxItem',{text:'same'});
   const combo=node('combo','ComboBox',{editable:false,enabled:true,selected:'one',text:'same'},[first,second],{choose:'choice'});
   const editor=node('editor','ComboBox',{editable:true,enabled:true,selected:null,text:''},[],{edit:'edit'});
   const root=node('root','Window',{title:'Control test'},[checkbox,a,b,combo,editor]);
   let rev=0;const apply=processed=>r.apply({mode:'snapshot',base_rev:null,rev:++rev,processed_seq:processed,roots:[root],bindings:root.children.length?[slot]:[],canvases:[]});
   apply(0);
   const c=r.elements.get('check').firstElementChild;c.click();c.click();
   checkbox.props.checked=true;apply(1);check(!c.checked,'Older checkbox reply overwrote later local toggle');
   checkbox.props.checked=false;apply(2);check(!c.checked && r.controlEdits.size===0,'Checkbox confirmation did not clear pending state');
   const rb=r.elements.get('b').firstElementChild;rb.click();
   apply(2);check(rb.checked && !r.elements.get('a').firstElementChild.checked,'Old radio reply overwrote selection');
   a.props.checked=false;b.props.checked=true;apply(3);
   const select=r.combos.get('combo').select;select.value='two';select.dispatchEvent(new Event('change'));
   apply(3);check(select.value==='two','Older combo reply overwrote choice');
   combo.props.selected='two';apply(4);check(select.value==='two','Choice confirmation changed selected duplicate label');
   const input=r.combos.get('editor').input;
   input.focus();input.value='draft';input.dispatchEvent(new InputEvent('input'));
   check(actions.length===4,'Editable combo sent while typing');
   input.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter'}));
   check(actions.length===5 && actions[4].body.data.value==='draft','Enter/blur submitted more than once');
   input.focus();input.value='newer';input.dispatchEvent(new InputEvent('input'));
   editor.props.text='DRAFT';apply(5);check(input.value==='newer','Server readback overwrote newer typing');
   input.blur();editor.props.text='NEWER';apply(6);check(input.value==='NEWER','Normalized committed text was not read back');
   input.focus();input.value='obsolete';input.dispatchEvent(new InputEvent('input'));
   editor.events.edit='rebound';editor.props.text='replacement';apply(6);
   check(input.value==='replacement','Rebinding retained an obsolete draft');
   combo.props.editable=true;combo.events={edit:'edit-combo'};apply(6);
   check(r.combos.get('combo').list.children.length===2 && r.elements.get('two').value==='same','Mode switch lost datalist options');
   combo.props.editable=false;combo.events={choose:'choose-again'};apply(6);
   check(select.value==='two','Mode switch lost selected duplicate option');
   combo.props.enabled=false;editor.props.enabled=false;apply(6);
   check(select.disabled && input.disabled,'Disabled controls still enabled');
   root.children=[];apply(6); // prune the now-unused slot along with controls
   r.destroy();host.remove();
  });
  assert.deepEqual(errors,[]);console.log('Native controls: cookbook models/keyboard, typed labels, Enter/blur, pending selections, newer drafts, rebind and editable mode changes passed.');
 } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
